"""Server-only allowlisted events. The caller owns the business transaction."""

from uuid import UUID

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.db.models import User
from app.domain.audit.models import AuditEvent

# There is deliberately no arbitrary metadata argument or client write endpoint.
ACTIONS = {
    "organization.member.role_updated": ("user", "succeeded"),
    "auth.signup.completed": ("user", "succeeded"),
    "auth.login": ("session", "succeeded"),
    "auth.logout": ("session", "succeeded"),
    "auth.session.revoked": ("session", "succeeded"),
    "workflow.created": ("workflow", "succeeded"),
    "workflow.updated": ("workflow", "succeeded"),
    "document.scan.clean": ("document", "succeeded"),
    "document.scan.rejected": ("document", "failed"),
    "document.scan.error": ("document", "failed"),
    "document.created": ("document", "succeeded"),
    "document.intake.completed": ("document", "succeeded"),
    "document.intake.failed": ("document", "failed"),
    "access.denied": ("access", "denied"),
}


async def record(
    db: AsyncSession,
    *,
    organization_id: UUID,
    actor_user_id: UUID,
    action: str,
    request_id: str,
    resource_id: UUID | None = None,
) -> None:
    resource_type, outcome = ACTIONS[action]
    # Correlation is generated by our middleware, never taken from a client header.
    correlation = str(UUID(request_id))
    if resource_id is not None and not isinstance(resource_id, UUID):
        raise ValueError("Audit targets must be opaque UUIDs")
    owner = await db.scalar(
        select(User.id).where(User.id == actor_user_id, User.organization_id == organization_id)
    )
    if owner is None:
        raise ValueError("Audit actor must belong to the recorded tenant")
    db.add(
        AuditEvent(
            organization_id=organization_id,
            actor_user_id=actor_user_id,
            action=action,
            resource_type=resource_type,
            resource_id=str(resource_id) if resource_id else None,
            request_id=correlation,
            details={"outcome": outcome},
        )
    )
    await db.flush()
